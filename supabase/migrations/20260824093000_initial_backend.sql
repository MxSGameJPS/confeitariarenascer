create or replace function public.create_order_transaction(
  p_customer jsonb,
  p_order jsonb,
  p_items jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_customer_id uuid;
  v_order public.orders;
begin
  insert into public.customers (name, phone)
  values (
    p_customer->>'name',
    p_customer->>'phone'
  )
  on conflict (phone) do update
  set
    name = excluded.name,
    updated_at = now()
  returning id into v_customer_id;

  insert into public.orders (
    customer_id,
    fulfillment_type,
    payment_method,
    subtotal,
    delivery_fee,
    total,
    change_for,
    address_street,
    address_number,
    address_neighborhood,
    address_complement,
    address_reference,
    notes
  )
  values (
    v_customer_id,
    p_order->>'fulfillment_type',
    p_order->>'payment_method',
    (p_order->>'subtotal')::numeric,
    coalesce((p_order->>'delivery_fee')::numeric, 0),
    (p_order->>'total')::numeric,
    nullif(p_order->>'change_for', '')::numeric,
    p_order#>>'{address,street}',
    p_order#>>'{address,number}',
    p_order#>>'{address,neighborhood}',
    p_order#>>'{address,complement}',
    p_order#>>'{address,reference}',
    p_order->>'notes'
  )
  returning * into v_order;

  insert into public.order_items (
    order_id,
    product_id,
    product_name,
    unit_price,
    quantity,
    subtotal
  )
  select
    v_order.id,
    (item->>'product_id')::uuid,
    item->>'product_name',
    (item->>'unit_price')::numeric,
    (item->>'quantity')::integer,
    (item->>'subtotal')::numeric
  from jsonb_array_elements(p_items) as item;

  return jsonb_build_object(
    'id', v_order.id,
    'order_number', v_order.order_number,
    'status', v_order.status,
    'payment_status', v_order.payment_status,
    'created_at', v_order.created_at
  );
end;
$$;

revoke execute on function public.create_order_transaction(jsonb, jsonb, jsonb) from public;
revoke execute on function public.create_order_transaction(jsonb, jsonb, jsonb) from anon;
revoke execute on function public.create_order_transaction(jsonb, jsonb, jsonb) from authenticated;
grant execute on function public.create_order_transaction(jsonb, jsonb, jsonb) to service_role;
